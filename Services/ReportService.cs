using System.Globalization;
using System.Text;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using TruckMate.Domain;
using TruckMate.Models;

namespace TruckMate.Services;

public class ReportService
{
    public byte[] BuildPdf(ReportResultViewModel r, AppSettings settings)
    {
        return Document.Create(doc =>
        {
            doc.Page(page =>
            {
                page.Size(PageSizes.A4.Landscape());
                page.Margin(24);
                page.DefaultTextStyle(x => x.FontSize(8));

                page.Header().Column(c =>
                {
                    c.Item().AlignCenter().Text("Weighbridge Transaction Report").FontSize(14).Bold();
                    c.Item().Text("Operator Transaction Report").FontSize(10).SemiBold();
                    c.Item().PaddingTop(4).Row(row =>
                    {
                        row.RelativeItem().Text($"Document No : {r.DocumentNo}");
                        row.RelativeItem().AlignRight().Text($"Generated On : {r.GeneratedOn:dd-MM-yyyy HH:mm}");
                    });
                    c.Item().PaddingTop(4).Text($"Applied Filters : {FilterText(r)}").FontSize(8).Italic();
                    c.Item().PaddingTop(4).Text($"Total Transactions {r.TotalRecords}   |   Pending {r.CountPending}   |   Completed {r.CountCompleted}   |   Not completed {r.CountNotCompleted}   |   Cancelled {r.CountCancelled}");
                    c.Item().Text($"Total Net Weight : {r.TotalNetWeight:N0} kg").Bold();
                    c.Item().PaddingTop(2).LineHorizontal(1);
                });

                page.Content().PaddingTop(6).Table(table =>
                {
                    table.ColumnsDefinition(cols =>
                    {
                        cols.ConstantColumn(22);
                        cols.ConstantColumn(58);
                        cols.ConstantColumn(58);
                        cols.ConstantColumn(55);
                        cols.ConstantColumn(38);
                        cols.ConstantColumn(70);
                        cols.ConstantColumn(70);
                        cols.ConstantColumn(45);
                        cols.ConstantColumn(45);
                        cols.ConstantColumn(45);
                        cols.ConstantColumn(62);
                    });

                    table.Header(h =>
                    {
                        void H(string t) => h.Cell().Background(Colors.Grey.Lighten2).Border(0.5f).BorderColor(Colors.Grey.Medium).Padding(2).Text(t).Bold();
                        H("NO"); H("TICKET"); H("DATE"); H("VEHICLE"); H("DIR"); H("SUPPLIER"); H("MATERIAL");
                        H("1ST KG"); H("2ND KG"); H("NET KG"); H("STATUS");
                    });

                    var i = 0;
                    foreach (var t in r.Rows)
                    {
                        i++;
                        void C(string t) => table.Cell().Border(0.5f).BorderColor(Colors.Grey.Medium).Padding(2).Text(t);
                        C(i.ToString(CultureInfo.InvariantCulture));
                        C(t.TicketNo);
                        C(t.FirstWeighedAt.ToLocalTime().ToString("dd-MM-yyyy", CultureInfo.InvariantCulture));
                        C(t.VehicleNo);
                        C(t.Direction.ToString());
                        C(t.Supplier ?? "");
                        C(t.Material?.Name ?? "");
                        C(t.FirstWeight.ToString("#,##0", CultureInfo.InvariantCulture));
                        C(t.SecondWeight?.ToString("#,##0", CultureInfo.InvariantCulture) ?? "-");
                        C(t.NetWeight?.ToString("#,##0", CultureInfo.InvariantCulture) ?? "-");
                        C(t.Status.ToString());
                    }
                });

                page.Footer().Row(row =>
                {
                    row.RelativeItem().Text("Generated by TruckMate Weighbridge Management System").FontSize(7).FontColor(Colors.Grey.Darken1);
                    row.ConstantItem(80).AlignRight().Text(x =>
                    {
                        x.CurrentPageNumber();
                        x.Span(" / ");
                        x.TotalPages();
                    });
                });
            });
        }).GeneratePdf();
    }

    public byte[] BuildCsv(ReportResultViewModel r)
    {
        var sb = new StringBuilder();
        sb.AppendLine("Ticket,Date,Vehicle,Direction,Supplier,Material,1stKg,2ndKg,NetKg,Status");
        foreach (var t in r.Rows)
        {
            string Q(string? v) => "\"" + (v ?? "").Replace("\"", "\"\"") + "\"";
            sb.AppendLine(string.Join(",",
                Q(t.TicketNo),
                Q(t.FirstWeighedAt.ToLocalTime().ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)),
                Q(t.VehicleNo),
                Q(t.Direction.ToString()),
                Q(t.Supplier),
                Q(t.Material?.Name),
                Q(t.FirstWeight.ToString("0.###", CultureInfo.InvariantCulture)),
                Q(t.SecondWeight?.ToString("0.###", CultureInfo.InvariantCulture) ?? ""),
                Q(t.NetWeight?.ToString("0.###", CultureInfo.InvariantCulture) ?? ""),
                Q(t.Status.ToString())));
        }
        return Encoding.UTF8.GetBytes(sb.ToString());
    }

    private static string FilterText(ReportResultViewModel r)
    {
        var f = r.Filter;
        var parts = new List<string>();
        if (f.From is not null) parts.Add($"From {f.From:dd-MM-yyyy}");
        if (f.To is not null) parts.Add($"To {f.To:dd-MM-yyyy}");
        if (!string.IsNullOrWhiteSpace(f.VehicleNo)) parts.Add($"Vehicle {f.VehicleNo}");
        if (!string.IsNullOrWhiteSpace(f.Direction)) parts.Add($"Direction {f.Direction}");
        if (!string.IsNullOrWhiteSpace(f.Supplier)) parts.Add($"Supplier {f.Supplier}");
        if (!string.IsNullOrWhiteSpace(f.Material)) parts.Add($"Material {f.Material}");
        if (!string.IsNullOrWhiteSpace(f.Transporter)) parts.Add($"Transporter {f.Transporter}");
        if (!string.IsNullOrWhiteSpace(f.Status)) parts.Add($"Status {f.Status}");
        if (parts.Count == 0) parts.Add("AllTransactions");
        return string.Join(", ", parts);
    }
}
